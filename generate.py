import re
import shutil
from pathlib import Path
from urllib.parse import unquote, urlsplit

import frontmatter
from markdown_it import MarkdownIt
from markupsafe import escape

ROOT = Path(__file__).resolve().parent
POSTS_DIR = ROOT / "posts"
PUBLIC_DIR = ROOT / "public"
LAYOUT_PATH = ROOT / "src" / "layout.html"
POST_INDEX = "index.md"

SITE_NAME = "guruprasadah's blog"
SITE_DESCRIPTION = "I'm Guruprasad AH, programmer and Friendly Neighbor Computer Mechanic."
GENERATED_MARKER = "<!-- generated by generate.py -->"

SHELL_FIX_SCRIPT = """<script>
    (() => {
        const fixShell = () => {
            const main = document.getElementById('main');
            if (!main) return;

            // Older cached pages may have the pre-responsive shell classes.
            // Keep the shell fluid until those pages pick up the new markup.
            if (getComputedStyle(main).maxWidth === 'none') {
                main.style.width = '100%';
                main.style.maxWidth = '50rem';
                main.style.minWidth = '0';
            }
        };

        fixShell();

        if (!window.__blogShellFixInstalled) {
            window.__blogShellFixInstalled = true;
            document.body.addEventListener('htmx:afterSwap', fixShell);
            document.body.addEventListener('htmx:historyRestore', fixShell);
        }
    })();
</script>"""

md = MarkdownIt("gfm-like")
default_fence = md.renderer.fence  # type: ignore


def render_fence(self, tokens, idx, options, env):
    token = tokens[idx]

    if token.info.strip() == "mermaid":
        return f'<div class="not-prose"><div class="mermaid">{escape(token.content)}</div></div>\n'

    return default_fence(tokens, idx, options, env)


md.add_render_rule("fence", render_fence)


def site_base_url():
    cname = ROOT / "CNAME"
    if cname.is_file():
        host = cname.read_text(encoding="utf-8").strip()
        if host:
            return f"https://{host}"
    return ""


SITE_BASE_URL = site_base_url()


def absolute_url(path):
    return f"{SITE_BASE_URL}{path}" if SITE_BASE_URL else path


def validate_post_images(bundle_dir, source, tokens):
    """Check that local images stay inside the post bundle and exist.

    Post assets live next to the post's index.md, so a reference such as
    ``images/diagram.png`` works both in the generated page and when the
    Markdown source is previewed.
    """
    bundle_dir = bundle_dir.resolve()

    for token in tokens:
        for child in token.children or []:
            if child.type != "image":
                continue

            src = child.attrGet("src") or ""
            if not src or src.startswith("#"):
                continue

            parsed = urlsplit(src)
            if parsed.scheme or parsed.netloc:
                continue  # Remote or data: URL, nothing local to check.

            if src.startswith("/"):
                raise ValueError(
                    f"{source}: image {src!r} must be inside its post "
                    "directory, not root-absolute"
                )

            target = (bundle_dir / unquote(parsed.path)).resolve()
            if not target.is_relative_to(bundle_dir):
                raise ValueError(
                    f"{source}: image {src!r} points outside the post directory"
                )
            if not target.is_file():
                raise ValueError(
                    f"{source}: image {src!r} not found (expected "
                    f"{target.relative_to(bundle_dir)})"
                )


def load_post(path):
    bundle_dir = path.parent
    source = path.relative_to(ROOT)
    slug = bundle_dir.name

    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise ValueError(
            f"{source}: the post directory name is its URL slug and must contain "
            "only lowercase letters, numbers, and single hyphens"
        )

    post = frontmatter.loads(path.read_text(encoding="utf-8"))

    declared_slug = post.metadata.get("slug")
    if declared_slug is not None and str(declared_slug) != slug:
        raise ValueError(
            f"{source}: frontmatter slug {declared_slug!r} must match the post "
            f"directory name {slug!r}"
        )

    title = str(post.metadata.get("title") or slug)

    if post.metadata.get("published") is None:
        raise ValueError(f"{source}: missing 'published' in frontmatter")

    wip = post.metadata.get("wip", False)
    if not isinstance(wip, bool):
        raise ValueError(f"{source}: 'wip' must be true or false")

    description = post.metadata.get("description")

    env = {}
    tokens = md.parse(post.content, env)
    validate_post_images(bundle_dir, source, tokens)

    return {
        "source": str(source),
        "slug": slug,
        "title": title,
        "published": str(post.metadata["published"]),
        "description": str(description) if description else "",
        "wip": wip,
        "html": md.renderer.render(tokens, md.options, env),
    }


def render_post_content(post):
    page_title = f"{post['title']} — {SITE_NAME}"

    return f"""<div id='content' class='w-full min-w-0 pt-5 flex flex-col items-center' data-page-title='{escape(page_title)}'>
        <div class='w-full flex justify-end px-2'>
            <a class='text-blue-600' href='../../index.html' hx-get='../../' hx-select='#main' hx-target='#main' hx-swap='outerHTML' hx-push-url='true'>&crarr; home</a>
        </div>
        <div class='prose px-2 w-full min-w-0'>
            <h1>{escape(post['title'])}</h1>
            <span>Published {escape(post['published'])}</span>
            <div>{post['html']}</div>
        </div>
        {SHELL_FIX_SCRIPT}
    </div>"""


def render_home_content(posts):
    post_list = "".join(
        [
            (
                "<span class='flex justify-between w-full'>"
                f"<a href='posts/{post['slug']}/index.html' hx-get='posts/{post['slug']}/' hx-select='#main' hx-target='#main' hx-swap='outerHTML' hx-push-url='true' class='text-blue-600'>{escape(post['title'])}</a>"
                f" <span>{escape(post['published'])}</span>"
                "</span>"
            )
            for post in posts
        ]
    )

    return f"""<div id='content' class='px-2 w-full min-w-0' data-page-title='{escape(SITE_NAME)}'>{post_list}
        {SHELL_FIX_SCRIPT}
    </div>"""


def render_meta(og_title, description, canonical_path, og_type):
    tags = [
        f'<meta property="og:title" content="{escape(og_title)}">',
        f'<meta property="og:type" content="{og_type}">',
        f'<meta property="og:site_name" content="{escape(SITE_NAME)}">',
    ]

    if description:
        tags.insert(0, f'<meta name="description" content="{escape(description)}">')
        tags.append(f'<meta property="og:description" content="{escape(description)}">')

    if canonical_path is not None:
        url = str(escape(absolute_url(canonical_path)))
        tags.append(f'<link rel="canonical" href="{url}">')
        tags.append(f'<meta property="og:url" content="{url}">')

    return "\n  ".join(tags)


def render_page(
    title,
    content,
    description="",
    canonical_path=None,
    og_type="website",
    og_title=None,
    base="",
):
    layout = LAYOUT_PATH.read_text(encoding="utf-8")
    replacements = {
        "TITLE": str(escape(title)),
        "META": render_meta(
            og_title or title, description, canonical_path, og_type
        ),
        "BASE": base,
        "CONTENT": content,
    }

    return re.sub(
        r"\{\{([A-Z]+)\}\}",
        lambda match: replacements.get(match.group(1), match.group(0)),
        layout,
    )


def write_page(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def clean_generated_post_pages():
    """Remove page files left behind by posts that were renamed or deleted.

    Only the generated index.html is removed. The post's source index.md and
    anything else in the directory (for example images/) are left alone.
    """
    for entry in POSTS_DIR.iterdir():
        if not entry.is_dir():
            continue

        index = entry / "index.html"
        if index.is_file() and GENERATED_MARKER in index.read_text(encoding="utf-8"):
            index.unlink()
            try:
                entry.rmdir()
            except OSError:
                pass


def clean_legacy_fragments():
    """Remove the old fragment-only output; posts are now full pages."""
    legacy_posts = PUBLIC_DIR / "posts"
    if legacy_posts.is_dir():
        shutil.rmtree(legacy_posts)

    legacy_index = PUBLIC_DIR / "posts.html"
    if legacy_index.is_file():
        legacy_index.unlink()


def post_sources():
    """Return the index.md path for every post bundle in posts/."""
    sources = []

    for entry in sorted(POSTS_DIR.iterdir()):
        if entry.is_file() and entry.suffix == ".md":
            raise ValueError(
                f"{entry.relative_to(ROOT)}: posts are directories named after "
                f"their slug; move this file to posts/<slug>/{POST_INDEX}"
            )
        if entry.is_dir() and (entry / POST_INDEX).is_file():
            sources.append(entry / POST_INDEX)

    return sources


def main():
    posts = [load_post(path) for path in post_sources()]
    posts = [post for post in posts if not post["wip"]]

    posts_by_slug = {}
    for post in posts:
        if post["slug"] in posts_by_slug:
            other = posts_by_slug[post["slug"]]
            raise ValueError(
                f"Duplicate slug {post['slug']!r} in {other['source']} and {post['source']}"
            )
        posts_by_slug[post["slug"]] = post

    sorted_posts = sorted(posts, key=lambda post: (post["published"], post["slug"]))

    clean_generated_post_pages()
    clean_legacy_fragments()

    for post in sorted_posts:
        page = render_page(
            title=f"{post['title']} — {SITE_NAME}",
            og_title=post["title"],
            description=post["description"],
            canonical_path=f"/posts/{post['slug']}/",
            content=render_post_content(post),
            og_type="article",
            base="../../",
        )
        write_page(POSTS_DIR / post["slug"] / "index.html", page)

    home_page = render_page(
        title=SITE_NAME,
        description=SITE_DESCRIPTION,
        canonical_path="/",
        content=render_home_content(sorted_posts),
    )
    write_page(ROOT / "index.html", home_page)


if __name__ == "__main__":
    main()
