import re
import shutil
import unicodedata
from pathlib import Path

import frontmatter
from markdown_it import MarkdownIt
from markupsafe import escape

ROOT = Path(__file__).resolve().parent
POSTS_DIR = ROOT / "posts"
PUBLIC_DIR = ROOT / "public"
LAYOUT_PATH = ROOT / "src" / "layout.html"

SITE_NAME = "guruprasadah's blog"
SITE_DESCRIPTION = "I'm Guruprasad AH, programmer and Friendly Neighbor Computer Mechanic."
GENERATED_MARKER = "<!-- generated by generate.py -->"

md = MarkdownIt("gfm-like")
default_fence = md.renderer.fence  # type: ignore


def render_fence(self, tokens, idx, options, env):
    token = tokens[idx]

    if token.info.strip() == "mermaid":
        return f'<div class="not-prose"><div class="mermaid">{escape(token.content)}</div></div>\n'

    return default_fence(tokens, idx, options, env)


md.add_render_rule("fence", render_fence)


def slugify(value):
    normalized = unicodedata.normalize("NFKD", value)
    ascii_value = normalized.encode("ascii", "ignore").decode("ascii")
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", ascii_value).strip("-").lower()
    return slug or "post"


def site_base_url():
    cname = ROOT / "CNAME"
    if cname.is_file():
        host = cname.read_text(encoding="utf-8").strip()
        if host:
            return f"https://{host}"
    return ""


SITE_BASE_URL = site_base_url()


def absolute_url(path):
    return f"{SITE_BASE_URL}{path}" if SITE_BASE_URL else path


def load_post(path):
    post = frontmatter.loads(path.read_text(encoding="utf-8"))

    title = str(post.metadata.get("title") or path.stem)
    slug = str(post.metadata.get("slug") or slugify(title))

    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
        raise ValueError(
            f"{path.name}: slug {slug!r} must contain only lowercase letters, "
            "numbers, and single hyphens"
        )

    if post.metadata.get("published") is None:
        raise ValueError(f"{path.name}: missing 'published' in frontmatter")

    description = post.metadata.get("description")

    return {
        "source": path.name,
        "slug": slug,
        "title": title,
        "published": str(post.metadata["published"]),
        "description": str(description) if description else "",
        "html": md.render(post.content),
    }


def render_post_content(post):
    page_title = f"{post['title']} — {SITE_NAME}"

    return f"""<div id='content' class='w-full pt-5 flex flex-col items-center' data-page-title='{escape(page_title)}'>
        <div class='w-full flex justify-end px-2'>
            <a class='text-blue-600' href='/' hx-get='/' hx-select='#content' hx-target='#content' hx-swap='outerHTML' hx-push-url='true'>&crarr; home</a>
        </div>
        <div class='prose'>
            <h1>{escape(post['title'])}</h1>
            <span>Published {escape(post['published'])}</span>
            <div>{post['html']}</div>
        </div>
    </div>"""


def render_home_content(posts):
    post_list = "".join(
        [
            (
                "<span class='flex justify-between w-full'>"
                f"<a href='/posts/{post['slug']}/' hx-get='/posts/{post['slug']}/' hx-select='#content' hx-target='#content' hx-swap='outerHTML' hx-push-url='true' class='text-blue-600'>{escape(post['title'])}</a>"
                f" <span>{escape(post['published'])}</span>"
                "</span>"
            )
            for post in posts
        ]
    )

    return f"""<div id='content' class='px-2 w-full' data-page-title='{escape(SITE_NAME)}'>{post_list}</div>"""


def render_meta(og_title, description, canonical_path, og_type):
    tags = [
        f'<meta property="og:title" content="{escape(og_title)}">',
        f'<meta property="og:type" content="{og_type}">',
        f'<meta property="og:site_name" content="{escape(SITE_NAME)}">',
    ]

    if description:
        tags.insert(0, f'<meta name="description" content="{escape(description)}">')
        tags.append(f'<meta property="og:description" content="{escape(description)}">')

    if canonical_path is not None:
        url = str(escape(absolute_url(canonical_path)))
        tags.append(f'<link rel="canonical" href="{url}">')
        tags.append(f'<meta property="og:url" content="{url}">')

    return "\n  ".join(tags)


def render_page(
    title, content, description="", canonical_path=None, og_type="website", og_title=None
):
    layout = LAYOUT_PATH.read_text(encoding="utf-8")
    replacements = {
        "TITLE": str(escape(title)),
        "META": render_meta(
            og_title or title, description, canonical_path, og_type
        ),
        "CONTENT": content,
    }

    return re.sub(
        r"\{\{([A-Z]+)\}\}",
        lambda match: replacements.get(match.group(1), match.group(0)),
        layout,
    )


def write_page(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def clean_generated_post_pages():
    """Remove page files left behind by posts that were renamed or deleted.

    Only the generated index.html is removed. Anything else in the directory
    (for example per-post images) is left alone.
    """
    for entry in POSTS_DIR.iterdir():
        if not entry.is_dir():
            continue

        index = entry / "index.html"
        if index.is_file() and GENERATED_MARKER in index.read_text(encoding="utf-8"):
            index.unlink()
            try:
                entry.rmdir()
            except OSError:
                pass


def clean_legacy_fragments():
    """Remove the old fragment-only output; posts are now full pages."""
    legacy_posts = PUBLIC_DIR / "posts"
    if legacy_posts.is_dir():
        shutil.rmtree(legacy_posts)

    legacy_index = PUBLIC_DIR / "posts.html"
    if legacy_index.is_file():
        legacy_index.unlink()


def main():
    posts = [
        load_post(path)
        for path in sorted(POSTS_DIR.iterdir())
        if path.is_file() and path.suffix == ".md"
    ]

    posts_by_slug = {}
    for post in posts:
        if post["slug"] in posts_by_slug:
            other = posts_by_slug[post["slug"]]
            raise ValueError(
                f"Duplicate slug {post['slug']!r} in {other['source']} and {post['source']}"
            )
        posts_by_slug[post["slug"]] = post

    sorted_posts = sorted(posts, key=lambda post: (post["published"], post["slug"]))

    clean_generated_post_pages()
    clean_legacy_fragments()

    for post in sorted_posts:
        page = render_page(
            title=f"{post['title']} — {SITE_NAME}",
            og_title=post["title"],
            description=post["description"],
            canonical_path=f"/posts/{post['slug']}/",
            content=render_post_content(post),
            og_type="article",
        )
        write_page(POSTS_DIR / post["slug"] / "index.html", page)

    home_page = render_page(
        title=SITE_NAME,
        description=SITE_DESCRIPTION,
        canonical_path="/",
        content=render_home_content(sorted_posts),
    )
    write_page(ROOT / "index.html", home_page)


if __name__ == "__main__":
    main()
